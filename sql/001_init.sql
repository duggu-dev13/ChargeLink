-- ChargeLink schema v1 (PostgreSQL 16)
DROP TABLE IF EXISTS alerts, ocpp_messages, status_events, meter_values,
                     transactions, id_tags, connectors, charge_points CASCADE;

CREATE TABLE charge_points (
    id                text PRIMARY KEY CHECK (id ~ '^[A-Za-z0-9_.-]{1,48}$'),
    vendor            text,
    model             text,
    serial_number     text,
    firmware_version  text,
    first_seen_at     timestamptz NOT NULL DEFAULT now(),
    last_boot_at      timestamptz,
    last_heartbeat_at timestamptz,
    online            boolean     NOT NULL DEFAULT false
);

CREATE TABLE connectors (
    charge_point_id text NOT NULL REFERENCES charge_points(id) ON DELETE CASCADE,
    connector_id    int  NOT NULL CHECK (connector_id >= 1),
    status          text NOT NULL DEFAULT 'Unavailable',
    error_code      text NOT NULL DEFAULT 'NoError',
    updated_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (charge_point_id, connector_id)
);

CREATE TABLE id_tags (
    id_tag     text PRIMARY KEY,
    status     text NOT NULL DEFAULT 'Accepted'
               CHECK (status IN ('Accepted','Blocked','Expired','Invalid')),
    expires_at timestamptz
);

CREATE TABLE transactions (
    id              integer GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    charge_point_id text NOT NULL,
    connector_id    int  NOT NULL,
    id_tag          text NOT NULL,
    meter_start_wh  bigint NOT NULL CHECK (meter_start_wh >= 0),
    meter_stop_wh   bigint,
    started_at      timestamptz NOT NULL,
    stopped_at      timestamptz,
    stop_reason     text,
    FOREIGN KEY (charge_point_id, connector_id)
        REFERENCES connectors(charge_point_id, connector_id),
    CONSTRAINT stop_consistent CHECK (
        (stopped_at IS NULL AND meter_stop_wh IS NULL) OR
        (stopped_at IS NOT NULL AND meter_stop_wh IS NOT NULL
         AND meter_stop_wh >= meter_start_wh AND stopped_at >= started_at))
);
-- At most ONE open transaction per connector, enforced by the database itself.
CREATE UNIQUE INDEX one_open_tx_per_connector
    ON transactions (charge_point_id, connector_id) WHERE stopped_at IS NULL;
CREATE INDEX tx_cp_started ON transactions (charge_point_id, started_at DESC);

CREATE TABLE meter_values (
    id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    charge_point_id text NOT NULL REFERENCES charge_points(id) ON DELETE CASCADE,
    transaction_id  integer REFERENCES transactions(id),
    ts              timestamptz NOT NULL,
    measurand       text NOT NULL DEFAULT 'Energy.Active.Import.Register',
    value           numeric NOT NULL,
    unit            text NOT NULL DEFAULT 'Wh'
);
CREATE INDEX mv_cp_ts ON meter_values (charge_point_id, ts DESC);
CREATE INDEX mv_tx    ON meter_values (transaction_id) WHERE transaction_id IS NOT NULL;

CREATE TABLE status_events (
    id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    charge_point_id text NOT NULL REFERENCES charge_points(id) ON DELETE CASCADE,
    connector_id    int  NOT NULL,
    status          text NOT NULL,
    error_code      text NOT NULL DEFAULT 'NoError',
    ts              timestamptz NOT NULL
);
CREATE INDEX se_cp_ts ON status_events (charge_point_id, ts DESC);

CREATE TABLE ocpp_messages (            -- audit trail of every frame
    id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    charge_point_id text NOT NULL,
    ts              timestamptz NOT NULL DEFAULT now(),
    direction       text NOT NULL CHECK (direction IN ('in','out')),
    msg_type        smallint NOT NULL CHECK (msg_type IN (2,3,4)),
    action          text,
    payload         jsonb NOT NULL
);
CREATE INDEX om_cp_ts ON ocpp_messages (charge_point_id, ts DESC);

CREATE TABLE alerts (
    id              bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    charge_point_id text NOT NULL REFERENCES charge_points(id) ON DELETE CASCADE,
    kind            text NOT NULL,
    severity        text NOT NULL CHECK (severity IN ('info','warning','critical')),
    message         text NOT NULL,
    raised_at       timestamptz NOT NULL DEFAULT now(),
    resolved_at     timestamptz
);
CREATE UNIQUE INDEX one_open_alert_per_kind
    ON alerts (charge_point_id, kind) WHERE resolved_at IS NULL;

